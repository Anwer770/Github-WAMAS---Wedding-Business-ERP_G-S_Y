import React, { useState, useEffect } from 'react';
import { StorageService, AppState } from './services/storageService';
import { Header } from './components/Header';
import { Sidebar, NavTab } from './components/Sidebar';
import { DashboardView } from './components/views/DashboardView';
import { BookingCalendarView } from './components/views/BookingCalendarView';
import { RentalContractsView } from './components/views/RentalContractsView';
import { InspectionSideBySideView } from './components/views/InspectionSideBySideView';
import { InventoryUnitsView } from './components/views/InventoryUnitsView';
import { CollateralVaultView } from './components/views/CollateralVaultView';
import { TaskKanbanView } from './components/views/TaskKanbanView';
import { PosCashierView } from './components/views/PosCashierView';
import { AccountingView } from './components/views/AccountingView';
import { CrmCustomersView } from './components/views/CrmCustomersView';
import { KoshaProjectsView } from './components/views/KoshaProjectsView';
import { ManufacturingView } from './components/views/ManufacturingView';
import { SuppliersPurchasingView } from './components/views/SuppliersPurchasingView';
import { PermissionsMatrixView } from './components/views/PermissionsMatrixView';
import { SystemSettingsView } from './components/views/SystemSettingsView';
import { DatabaseSchemaView } from './components/views/DatabaseSchemaView';
import { AcceptanceTestsView } from './components/views/AcceptanceTestsView';
import { 
  User, Product, ProductUnit, Customer, Booking, RentalContract, 
  Collateral, Inspection, Task, Account, JournalEntry, ContractStage,
  ProductUnitStatus, TaskStatus, CustomerMeasurements
} from './types';
import { DoubleEntryAccountingService } from './services/doubleEntryAccountingService';
import { ContractLifecycleService } from './services/contractLifecycleService';

export default function App() {
  const [state, setState] = useState<AppState>(() => StorageService.loadState());
  const [activeTab, setActiveTab] = useState<NavTab>('DASHBOARD');
  const [searchQuery, setSearchQuery] = useState('');

  // Modals
  const [showNewTaskModal, setShowNewTaskModal] = useState(false);
  const [taskTitle, setTaskTitle] = useState('');
  const [taskDescription, setTaskDescription] = useState('');
  const [taskType, setTaskType] = useState<Task['taskType']>('PREPARATION');
  const [taskPriority, setTaskPriority] = useState<Task['priority']>('HIGH');
  const [taskAssignedToId, setTaskAssignedToId] = useState<string>(state.users[7]?.id || state.users[0]?.id);
  const [taskDueDate, setTaskDueDate] = useState<string>('2026-10-25T18:00');

  // Sync to persistence on state changes
  useEffect(() => {
    StorageService.saveState(state);
  }, [state]);

  // Derived counts for badges
  const overdueTasksCount = state.tasks.filter(
    t => new Date(t.dueDate).getTime() < Date.now() && t.status !== 'COMPLETED'
  ).length;

  const lateContractsCount = state.contracts.filter(c => c.daysLate > 0 && c.status === 'ACTIVE').length;
  const pendingInspectionsCount = state.units.filter(u => u.status === 'PENDING_INSPECTION').length;
  const heldCollateralCount = state.collaterals.filter(c => c.status === 'HELD').length;
  const activeTasksCount = state.tasks.filter(t => t.status !== 'COMPLETED').length;

  // Handlers
  const handleSwitchUser = (user: User) => {
    setState(prev => ({ ...prev, currentUser: user }));
  };

  const handleResetData = () => {
    const fresh = StorageService.resetToDefault();
    setState(fresh);
    alert('تمت استعادة كافة البيانات النموذجية بنجاح!');
  };

  const handleSaveBooking = (newBooking: Booking, updatedUnit: ProductUnit) => {
    // 1. Create Preparation Task automatically (BR-20)
    const newTask: Task = {
      id: `tsk-${Date.now()}`,
      taskNumber: `TASK-2026-${String(state.tasks.length + 101).padStart(4, '0')}`,
      title: `تجهيز وخياطة القطعة (${updatedUnit.serialNumber}) للحجز ${newBooking.bookingNumber}`,
      description: `تجهيز الصنف قبل موعد المناسبة في ${newBooking.startDate}`,
      taskType: 'PREPARATION',
      priority: 'HIGH',
      status: 'NEW',
      assignedToId: state.users.find(u => u.role === 'TAILOR')?.id || state.currentUser.id,
      assignedToName: state.users.find(u => u.role === 'TAILOR')?.name || 'الخياط المسؤول',
      createdById: state.currentUser.id,
      createdByName: state.currentUser.name,
      dueDate: new Date(new Date(newBooking.startDate).getTime() - 24 * 3600 * 1000).toISOString(),
      progressPercent: 0,
      entityType: 'BOOKING',
      entityId: newBooking.id,
      entityTitle: newBooking.bookingNumber,
      isAutoGenerated: true,
      triggerEvent: 'تأكيد الحجز وسداد العربون (BR-20)',
      attachments: [],
      comments: []
    };

    // 2. Create corresponding rental contract in stage 3 (Deposit Paid)
    const newContract: RentalContract = {
      id: `cnt-${Date.now()}`,
      contractNumber: `CONT-2026-${String(state.contracts.length + 101).padStart(4, '0')}`,
      bookingId: newBooking.id,
      customerId: newBooking.customerId,
      currentStage: 3, // Deposit Paid
      startDate: newBooking.startDate,
      expectedReturnDate: newBooking.endDate,
      daysLate: 0,
      latePenaltyFee: 0,
      damagePenaltyFee: 0,
      lostFee: 0,
      totalDeductions: 0,
      refundedCollateral: 0,
      additionalDueAmount: 0,
      deliveryInspectionDone: false,
      returnInspectionDone: false,
      status: 'ACTIVE',
      createdAt: new Date().toISOString()
    };

    setState(prev => ({
      ...prev,
      bookings: [newBooking, ...prev.bookings],
      contracts: [newContract, ...prev.contracts],
      units: prev.units.map(u => u.id === updatedUnit.id ? updatedUnit : u),
      tasks: [newTask, ...prev.tasks],
      auditLogs: [
        {
          id: `log-${Date.now()}`,
          timestamp: new Date().toISOString(),
          userId: state.currentUser.id,
          userName: state.currentUser.name,
          action: 'تأكيد حجز جديد',
          details: `تم تأكيد الحجز ${newBooking.bookingNumber} وقفل القطعة وتوليد مهمة الخياطة`
        },
        ...prev.auditLogs
      ]
    }));
  };

  const handleAdvanceContractStage = (contractId: string, targetStage: ContractStage) => {
    const contract = state.contracts.find(c => c.id === contractId);
    if (!contract) return;
    const booking = state.bookings.find(b => b.id === contract.bookingId);
    const item = booking?.items[0];
    const unit = state.units.find(u => u.id === item?.productUnitId);
    if (!booking || !unit) return;

    const transition = ContractLifecycleService.advanceStage(
      contract,
      booking,
      state.collaterals,
      state.inspections,
      unit
    );

    if (!transition.success) {
      alert(transition.error);
      return;
    }

    const updatedContracts = state.contracts.map(c => c.id === contractId ? transition.contract! : c);
    let updatedUnits = state.units;
    let updatedTasks = state.tasks;

    if (transition.automatedTrigger?.unitStatusChange) {
      const { unitId, newStatus, cleaningDurationHours } = transition.automatedTrigger.unitStatusChange;
      updatedUnits = updatedUnits.map(u => {
        if (u.id === unitId) {
          return {
            ...u,
            status: newStatus as ProductUnitStatus,
            cleaningDueUntil: cleaningDurationHours 
              ? new Date(Date.now() + cleaningDurationHours * 3600 * 1000).toISOString()
              : undefined
          };
        }
        return u;
      });
    }

    if (transition.automatedTrigger?.taskToCreate) {
      const tc = transition.automatedTrigger.taskToCreate;
      const assignedUser = state.users.find(u => u.role === tc.assignedRole) || state.users[0];
      const newTask: Task = {
        id: `tsk-${Date.now()}`,
        taskNumber: `TASK-2026-${String(state.tasks.length + 101).padStart(4, '0')}`,
        title: tc.title,
        taskType: tc.type as any,
        priority: tc.priority,
        status: 'NEW',
        assignedToId: assignedUser.id,
        assignedToName: assignedUser.name,
        createdById: state.currentUser.id,
        createdByName: state.currentUser.name,
        dueDate: new Date(Date.now() + tc.dueHours * 3600 * 1000).toISOString(),
        progressPercent: 0,
        entityType: 'CONTRACT',
        entityId: contract.id,
        entityTitle: contract.contractNumber,
        isAutoGenerated: true,
        triggerEvent: `انتقال العقد إلى المرحلة ${targetStage}`,
        attachments: [],
        comments: []
      };
      updatedTasks = [newTask, ...updatedTasks];
    }

    setState(prev => ({
      ...prev,
      contracts: updatedContracts,
      units: updatedUnits,
      tasks: updatedTasks
    }));

    alert(`تم بنجاح نقل العقد (${contract.contractNumber}) إلى المرحلة (${targetStage}) وتطبيق كافة الآثار التشغيلية!`);
  };

  const handleSaveInspection = (inspection: Inspection, contractUpdate?: Partial<RentalContract>) => {
    setState(prev => {
      let updatedContracts = prev.contracts;
      if (contractUpdate && inspection.contractId) {
        updatedContracts = updatedContracts.map(c => {
          if (c.id === inspection.contractId) {
            return { ...c, ...contractUpdate, returnInspectionDone: true };
          }
          return c;
        });
      }

      // If damage detected, generate repair task automatically
      let updatedTasks = prev.tasks;
      if (inspection.damageMarkers.length > 0) {
        const newTask: Task = {
          id: `tsk-${Date.now()}`,
          taskNumber: `TASK-2026-${String(prev.tasks.length + 101).padStart(4, '0')}`,
          title: `إصلاح وترميم تلفيات بعد الإرجاع للقطعة ${inspection.unitSerialNumber}`,
          description: `تلفيات مسجلة: ${inspection.damageMarkers.map(m => m.description).join('، ')}`,
          taskType: 'REPAIR',
          priority: 'URGENT',
          status: 'NEW',
          assignedToId: prev.users.find(u => u.role === 'TAILOR')?.id || prev.currentUser.id,
          assignedToName: prev.users.find(u => u.role === 'TAILOR')?.name || 'المشغل',
          createdById: prev.currentUser.id,
          createdByName: prev.currentUser.name,
          dueDate: new Date(Date.now() + 48 * 3600 * 1000).toISOString(),
          progressPercent: 0,
          entityType: 'CONTRACT',
          entityId: inspection.contractId,
          isAutoGenerated: true,
          triggerEvent: 'رصد تلفيات في تقرير الفحص المقارن',
          attachments: [],
          comments: []
        };
        updatedTasks = [newTask, ...updatedTasks];
      }

      return {
        ...prev,
        inspections: [inspection, ...prev.inspections.filter(i => i.id !== inspection.id)],
        contracts: updatedContracts,
        tasks: updatedTasks
      };
    });
  };

  const handleAddCollateral = (collateral: Collateral) => {
    // Also create journal entry for cash collateral
    let updatedAccounts = state.accounts;
    let updatedEntries = state.journalEntries;

    if (collateral.type === 'CASH' && collateral.amount) {
      const entryRes = DoubleEntryAccountingService.createCollateralReceivedEntry(
        collateral.receiptNumber,
        collateral.amount,
        collateral.customerName,
        state.accounts,
        state.currentUser.id
      );
      if (entryRes.success && entryRes.entry && entryRes.updatedAccounts) {
        updatedAccounts = entryRes.updatedAccounts;
        updatedEntries = [entryRes.entry, ...updatedEntries];
      }
    }

    setState(prev => ({
      ...prev,
      collaterals: [collateral, ...prev.collaterals],
      accounts: updatedAccounts,
      journalEntries: updatedEntries
    }));
  };

  const handleRefundCollateral = (collateralId: string) => {
    setState(prev => ({
      ...prev,
      collaterals: prev.collaterals.map(c => c.id === collateralId ? { ...c, status: 'REFUNDED', returnedAt: new Date().toISOString() } : c)
    }));
  };

  const handleUpdateTaskStatus = (taskId: string, newStatus: TaskStatus, proofUrl?: string) => {
    setState(prev => ({
      ...prev,
      tasks: prev.tasks.map(t => {
        if (t.id === taskId) {
          const attachments = proofUrl ? [
            ...t.attachments,
            {
              id: `att-${Date.now()}`,
              url: proofUrl,
              fileType: 'IMAGE' as const,
              isCompletionEvidence: true,
              uploadedAt: new Date().toISOString()
            }
          ] : t.attachments;
          return {
            ...t,
            status: newStatus,
            completedAt: newStatus === 'COMPLETED' ? new Date().toISOString() : t.completedAt,
            progressPercent: newStatus === 'COMPLETED' ? 100 : t.progressPercent,
            attachments
          };
        }
        return t;
      })
    }));
  };

  const handleRecordPayment = (
    voucherNumber: string,
    amount: number,
    method: string,
    customerName: string,
    category: string
  ) => {
    // Post balanced double-entry
    const entryRes = DoubleEntryAccountingService.postJournalEntry(
      `JE-${voucherNumber}`,
      `سند قبض ${voucherNumber} - ${customerName} (${category})`,
      'DEPOSIT',
      voucherNumber,
      [
        { accountId: '1', accountCode: method === 'CASH' ? '1101' : '1102', accountNameAr: method === 'CASH' ? 'الصندوق والخزينة' : 'البنك والشبكة', debit: amount, credit: 0, memo: `سند قبض ${voucherNumber}` },
        { accountId: '6', accountCode: '2201', accountNameAr: 'إيرادات الحجوزات المقدمة (عربون مؤجل)', debit: 0, credit: amount, memo: `عربون/دفعة من العميل ${customerName}` }
      ],
      state.accounts,
      state.currentUser.id
    );

    if (entryRes.success && entryRes.entry && entryRes.updatedAccounts) {
      setState(prev => ({
        ...prev,
        accounts: entryRes.updatedAccounts!,
        journalEntries: [entryRes.entry!, ...prev.journalEntries]
      }));
    }
  };

  const handleReverseEntry = (originalEntry: JournalEntry, reason: string) => {
    const rev = DoubleEntryAccountingService.createReversalEntry(
      originalEntry,
      state.accounts,
      state.currentUser.id,
      reason
    );

    if (rev.success && rev.reversalEntry && rev.updatedAccounts) {
      setState(prev => ({
        ...prev,
        accounts: rev.updatedAccounts!,
        journalEntries: [
          rev.reversalEntry!,
          ...prev.journalEntries.map(je => je.id === originalEntry.id ? { ...je, isReversed: true, reversalEntryId: rev.reversalEntry!.id } : je)
        ]
      }));
    }
  };

  const handleAddProduct = (newProduct: Product, initialUnit: ProductUnit) => {
    setState(prev => ({
      ...prev,
      products: [newProduct, ...prev.products],
      units: [initialUnit, ...prev.units]
    }));
  };

  const handleUpdateUnitStatus = (unitId: string, newStatus: ProductUnitStatus) => {
    setState(prev => ({
      ...prev,
      units: prev.units.map(u => u.id === unitId ? { ...u, status: newStatus } : u)
    }));
  };

  const handleAddCustomer = (newCustomer: Customer) => {
    setState(prev => ({
      ...prev,
      customers: [newCustomer, ...prev.customers]
    }));
  };

  const handleUpdateMeasurements = (customerId: string, measurements: CustomerMeasurements) => {
    setState(prev => ({
      ...prev,
      customers: prev.customers.map(c => c.id === customerId ? { ...c, measurements } : c)
    }));
  };

  const handleUpdateKoshaComponent = (projectId: string, compIdx: number) => {
    setState(prev => ({
      ...prev,
      koshaProjects: prev.koshaProjects.map(p => {
        if (p.id === projectId) {
          const list = [...p.componentsList];
          list[compIdx] = { ...list[compIdx], checked: !list[compIdx].checked };
          return { ...p, componentsList: list };
        }
        return p;
      })
    }));
  };

  const handleCreateManualTask = () => {
    if (!taskTitle) return;
    const assigned = state.users.find(u => u.id === taskAssignedToId) || state.users[0];
    const newTask: Task = {
      id: `tsk-${Date.now()}`,
      taskNumber: `TASK-2026-${String(state.tasks.length + 101).padStart(4, '0')}`,
      title: taskTitle,
      description: taskDescription,
      taskType,
      priority: taskPriority,
      status: 'NEW',
      assignedToId: assigned.id,
      assignedToName: assigned.name,
      createdById: state.currentUser.id,
      createdByName: state.currentUser.name,
      dueDate: new Date(taskDueDate).toISOString(),
      progressPercent: 0,
      isAutoGenerated: false,
      attachments: [],
      comments: []
    };

    setState(prev => ({ ...prev, tasks: [newTask, ...prev.tasks] }));
    setShowNewTaskModal(false);
    setTaskTitle('');
    setTaskDescription('');
  };

  const handleApplyLatePenalty = (
    contractId: string,
    daysLate: number,
    penaltyAmount: number,
    notes?: string
  ) => {
    const contract = state.contracts.find(c => c.id === contractId);
    if (!contract) return;
    const customer = state.customers.find(c => c.id === contract.customerId);

    // 1. Post Double-Entry Journal Entry
    // Debit: Collateral Liability (2101) - clearing collateral against penalty
    // Credit: Late Penalty Revenue (4201)
    const entryRes = DoubleEntryAccountingService.postJournalEntry(
      `JE-PENALTY-${contract.contractNumber}`,
      notes || `غرامة تأخير إرجاع عقد ${contract.contractNumber} (${daysLate} يوم)`,
      'SETTLEMENT',
      contract.contractNumber,
      [
        { accountId: '3', accountCode: '2101', accountNameAr: 'أمانات وتأمينات العملاء (Collateral Liability)', debit: penaltyAmount, credit: 0, memo: `خصم غرامة تأخير من أمانة العميل ${customer?.fullName}` },
        { accountId: '4', accountCode: '4201', accountNameAr: 'إيرادات غرامات التأخير', debit: 0, credit: penaltyAmount, memo: `إيراد غرامة تأخير عقد ${contract.contractNumber}` }
      ],
      state.accounts,
      state.currentUser.id
    );

    // 2. Create an urgent Collection / Retrieval Task
    const urgentTask: Task = {
      id: `tsk-${Date.now()}`,
      taskNumber: `TASK-2026-${String(state.tasks.length + 101).padStart(4, '0')}`,
      title: `متابعة وتحصيل غرامة تأخير عقد (${contract.contractNumber}) — العميل ${customer?.fullName}`,
      description: `تم فرض غرامة تأخير قدرها ${penaltyAmount} ر.س لتجاوز موعد الإرجاع بـ ${daysLate} يوم. مطلوب التواصل الفوري مع العميل وتنسيق استلام القطعة فوراً.`,
      taskType: 'COLLECTION',
      priority: 'URGENT',
      status: 'NEW',
      assignedToId: state.users.find(u => u.role === 'RENTAL_AGENT')?.id || state.currentUser.id,
      assignedToName: state.users.find(u => u.role === 'RENTAL_AGENT')?.name || 'موظف التأجير والمتابعة',
      createdById: state.currentUser.id,
      createdByName: state.currentUser.name,
      dueDate: new Date(Date.now() + 6 * 3600 * 1000).toISOString(),
      progressPercent: 0,
      entityType: 'CONTRACT',
      entityId: contract.id,
      entityTitle: contract.contractNumber,
      isAutoGenerated: true,
      triggerEvent: `توليد وتطبيق غرامة تأخير (${penaltyAmount} ر.س) لتجاوز الموعد بـ ${daysLate} يوم`,
      attachments: [],
      comments: []
    };

    // 3. Update contract deductions
    const collateralHeld = state.collaterals
      .filter(c => c.contractId === contract.id)
      .reduce((acc, c) => acc + (c.amount || c.goldEstimatedValue || 0), 0);

    const totalDeductions = contract.damagePenaltyFee + penaltyAmount + contract.lostFee;
    const refundedCollateral = Math.max(0, collateralHeld - totalDeductions);
    const additionalDueAmount = Math.max(0, totalDeductions - collateralHeld);

    const updatedContracts = state.contracts.map(c => {
      if (c.id === contractId) {
        return {
          ...c,
          daysLate,
          latePenaltyFee: penaltyAmount,
          totalDeductions,
          refundedCollateral,
          additionalDueAmount
        };
      }
      return c;
    });

    setState(prev => ({
      ...prev,
      contracts: updatedContracts,
      tasks: [urgentTask, ...prev.tasks],
      accounts: entryRes.success && entryRes.updatedAccounts ? entryRes.updatedAccounts : prev.accounts,
      journalEntries: entryRes.success && entryRes.entry ? [entryRes.entry, ...prev.journalEntries] : prev.journalEntries,
      auditLogs: [
        {
          id: `log-${Date.now()}`,
          timestamp: new Date().toISOString(),
          userId: state.currentUser.id,
          userName: state.currentUser.name,
          action: 'توليد غرامة تأخير',
          details: `تم تطبيق غرامة تأخير على العقد ${contract.contractNumber} بمبلغ ${penaltyAmount} ر.س (${daysLate} يوم) وتوليد مهمة تحصيل عاجلة`
        },
        ...prev.auditLogs
      ]
    }));
  };

  return (
    <div className="min-h-screen bg-slate-50 text-slate-900 flex flex-col font-sans selection:bg-purple-200 selection:text-purple-900">
      
      {/* Top Header */}
      <Header
        currentUser={state.currentUser}
        allUsers={state.users}
        onSwitchUser={handleSwitchUser}
        onOpenNewBookingModal={() => setActiveTab('BOOKINGS_CALENDAR')}
        onOpenNewTaskModal={() => setShowNewTaskModal(true)}
        onResetData={handleResetData}
        overdueTasksCount={overdueTasksCount}
        lateContractsCount={lateContractsCount}
        searchQuery={searchQuery}
        onSearchChange={setSearchQuery}
        syncStatus={state.syncStatus}
        outboxCount={state.outbox.length}
        lastSyncTime={state.lastSyncTime}
        onTriggerSync={() => {
          setState(prev => ({
            ...prev,
            syncStatus: 'SYNCING'
          }));
          setTimeout(() => {
            setState(prev => ({
              ...prev,
              syncStatus: 'ONLINE',
              lastSyncTime: 'الآن (متزامن)',
              outbox: []
            }));
          }, 1000);
        }}
      />

      {/* Main Layout Area */}
      <div className="flex-1 flex max-w-7xl w-full mx-auto">
        
        {/* Navigation Sidebar */}
        <Sidebar
          activeTab={activeTab}
          onSelectTab={setActiveTab}
          userRole={state.currentUser.role}
          pendingInspectionsCount={pendingInspectionsCount}
          activeTasksCount={activeTasksCount}
          heldCollateralCount={heldCollateralCount}
        />

        {/* Dynamic View Area */}
        <main className="flex-1 p-4 sm:p-6 lg:p-8 overflow-y-auto">
          {activeTab === 'DASHBOARD' && (
            <DashboardView
              state={state}
              onNavigate={setActiveTab}
              onApplyLatePenalty={handleApplyLatePenalty}
            />
          )}

          {activeTab === 'BOOKINGS_CALENDAR' && (
            <BookingCalendarView state={state} onSaveBooking={handleSaveBooking} />
          )}

          {activeTab === 'RENTAL_CONTRACTS' && (
            <RentalContractsView
              state={state}
              onAdvanceContractStage={handleAdvanceContractStage}
              onNavigateToInspection={() => setActiveTab('INSPECTION_SIDE_BY_SIDE')}
            />
          )}

          {activeTab === 'INSPECTION_SIDE_BY_SIDE' && (
            <InspectionSideBySideView state={state} onSaveInspection={handleSaveInspection} />
          )}

          {activeTab === 'INVENTORY_UNITS' && (
            <InventoryUnitsView
              state={state}
              onAddProduct={handleAddProduct}
              onUpdateUnitStatus={handleUpdateUnitStatus}
            />
          )}

          {activeTab === 'COLLATERAL_VAULT' && (
            <CollateralVaultView
              state={state}
              onAddCollateral={handleAddCollateral}
              onRefundCollateral={handleRefundCollateral}
            />
          )}

          {activeTab === 'TASKS_KANBAN' && (
            <TaskKanbanView
              state={state}
              onUpdateTaskStatus={handleUpdateTaskStatus}
              onOpenCreateTaskModal={() => setShowNewTaskModal(true)}
            />
          )}

          {activeTab === 'POS_CASHBOX' && (
            <PosCashierView state={state} onRecordPayment={handleRecordPayment} />
          )}

          {activeTab === 'ACCOUNTING_COA' && (
            <AccountingView
              state={state}
              onPostManualEntry={(entry, updatedAccounts) => {
                setState(prev => ({ ...prev, journalEntries: [entry, ...prev.journalEntries], accounts: updatedAccounts }));
              }}
              onReverseEntry={handleReverseEntry}
            />
          )}

          {activeTab === 'CRM_CUSTOMERS' && (
            <CrmCustomersView
              state={state}
              onAddCustomer={handleAddCustomer}
              onUpdateMeasurements={handleUpdateMeasurements}
            />
          )}

          {activeTab === 'KOSHA_PROJECTS' && (
            <KoshaProjectsView
              state={state}
              onUpdateComponentCheck={handleUpdateKoshaComponent}
            />
          )}

          {activeTab === 'MANUFACTURING' && (
            <ManufacturingView
              state={state}
              onUpdateState={setState}
              currentUserRole={state.currentUser.role}
            />
          )}

          {activeTab === 'SUPPLIERS_PURCHASING' && (
            <SuppliersPurchasingView
              state={state}
              onUpdateState={setState}
              currentUserRole={state.currentUser.role}
            />
          )}

          {activeTab === 'PERMISSIONS_RBAC' && (
            <PermissionsMatrixView
              state={state}
              onUpdateState={setState}
              currentUserRole={state.currentUser.role}
            />
          )}

          {activeTab === 'SYSTEM_SETTINGS' && (
            <SystemSettingsView
              state={state}
              onUpdateState={setState}
              currentUserRole={state.currentUser.role}
            />
          )}

          {activeTab === 'DB_SCHEMA' && (
            <DatabaseSchemaView />
          )}

          {activeTab === 'ACCEPTANCE_TESTS' && (
            <AcceptanceTestsView state={state} />
          )}
        </main>

      </div>

      {/* Manual Task Modal */}
      {showNewTaskModal && (
        <div className="fixed inset-0 bg-slate-900/60 backdrop-blur-sm z-50 flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-2xl border border-slate-200 text-right animate-in fade-in">
            <h3 className="font-bold text-sm text-slate-900 pb-3 border-b border-slate-100">
              إنشاء وتكليف بمهمة تشغيلية جديدة
            </h3>
            <div className="py-4 space-y-3">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">عنوان المهمة:</label>
                <input
                  type="text"
                  value={taskTitle}
                  onChange={(e) => setTaskTitle(e.target.value)}
                  placeholder="مثال: متابعة بروفة الفستان مع العروس..."
                  className="w-full text-xs p-2 rounded-lg border border-slate-300"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-bold text-slate-700 mb-1">نوع المهمة:</label>
                  <select
                    value={taskType}
                    onChange={(e) => setTaskType(e.target.value as any)}
                    className="w-full text-xs p-2 rounded-lg border border-slate-300"
                  >
                    <option value="PREPARATION">تجهيز وخياطة</option>
                    <option value="CLEANING">غسيل وكي</option>
                    <option value="DELIVERY">تسليم للعميل</option>
                    <option value="INSPECTION">فحص بعد الإرجاع</option>
                    <option value="ADMIN">إدارية ومتابعة</option>
                  </select>
                </div>
                <div>
                  <label className="block text-xs font-bold text-slate-700 mb-1">الأولوية:</label>
                  <select
                    value={taskPriority}
                    onChange={(e) => setTaskPriority(e.target.value as any)}
                    className="w-full text-xs p-2 rounded-lg border border-slate-300"
                  >
                    <option value="URGENT">عاجلة 🔴</option>
                    <option value="HIGH">عالية 🟠</option>
                    <option value="MEDIUM">متوسطة 🟡</option>
                    <option value="LOW">منخفضة 🟢</option>
                  </select>
                </div>
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">الموظف المكلَّف:</label>
                <select
                  value={taskAssignedToId}
                  onChange={(e) => setTaskAssignedToId(e.target.value)}
                  className="w-full text-xs p-2 rounded-lg border border-slate-300"
                >
                  {state.users.map(u => (
                    <option key={u.id} value={u.id}>{u.name} ({u.role})</option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">الموعد النهائي (Deadline):</label>
                <input
                  type="datetime-local"
                  value={taskDueDate}
                  onChange={(e) => setTaskDueDate(e.target.value)}
                  className="w-full text-xs p-2 rounded-lg border border-slate-300"
                />
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">التفاصيل والتعليمات:</label>
                <textarea
                  rows={2}
                  value={taskDescription}
                  onChange={(e) => setTaskDescription(e.target.value)}
                  className="w-full text-xs p-2 rounded-lg border border-slate-300"
                />
              </div>
            </div>

            <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
              <button onClick={() => setShowNewTaskModal(false)} className="px-4 py-2 border rounded-xl text-xs font-semibold text-slate-600">
                إلغاء
              </button>
              <button onClick={handleCreateManualTask} className="px-5 py-2 bg-purple-900 text-white rounded-xl text-xs font-bold hover:bg-purple-800">
                تعيين المهمة
              </button>
            </div>
          </div>
        </div>
      )}

    </div>
  );
}
